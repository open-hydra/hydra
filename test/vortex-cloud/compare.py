def table(results, run, gen):
    L = ['# vortex-cloud: ICE, IGLOO and the exact solution at a quarter turn', '',
         'St = Omega tau; C = z / z0 of the cloud centroid (|C| the dilation, lag = Omega t - arg C); slope =',
         'the mass-weighted du/dz against the exact C\'/C; L1 against the exact density on ICE\'s 96 x 96',
         'grid. ICE is measured at its own final time (its first step past QUARTER), IGLOO at QUARTER =',
         '%.10f s; each against the closed form at that time. IGLOO\'s deposit has the parcels\'' % run.QUARTER,
         'centroid by construction (the kernel keeps the first moment); its L1 is set by the kernel,',
         'whose floor (the exactly mapped lattice deposited the same way) is given beside it.', '',
         '| St | solver | t [s] | &#124;C&#124; | exact | error | lag [rad] | exact | error | slope error | L1 | kernel L1 | mass |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for r in results:
        for name, t, ratio, slope, C, Cd, l1, floor, mass in (
                ('ICE', r['ice'][-1]['t'], r['ice'][-1]['ratio'], r['ice'][-1]['slope'], r['ice'][-1]['C'],
                 r['ice'][-1]['Cd'], r['ice'][-1]['l1'], None, r['ice'][-1]['mass']),
                ('IGLOO parcels', r['T'], r['ratio'], r['slope'], r['C'], r['Cd'], None, None, None),
                ('IGLOO deposit', r['T'], r['dep_ratio'], r['dep_slope'], r['C'], r['Cd'], r['dep_l1'],
                 r['floor'], r['dep_mass'])):
            lag, xlag = run.OMEGA * t - cmath.phase(ratio), run.OMEGA * t - cmath.phase(C)
            L.append('| %g | %s | %.6f | %.6f | %.6f | %+.2e | %.6f | %.6f | %+.2e | %.2e | %s | %s | %s |' % (
                r['st'], name, t, abs(ratio), abs(C), abs(ratio) - abs(C), lag, xlag, lag - xlag,
                abs(slope / (Cd / C) - 1.0), '-' if l1 is None else '%.3e' % l1,
                '-' if floor is None else '%.3e' % floor, '-' if mass is None else '%+.1e' % mass))
    L += ['', 'ICE history (numbered solutions, sol-dtime = QUARTER/8), |C| / lag against the closed form at each time:', '',
          '| St | t [s] | &#124;C&#124; | exact | lag [rad] | exact | L1 |', '|---|---|---|---|---|---|---|']
    for r in results:
        for h in r['ice']:
            L.append('| %g | %.6f | %.6f | %.6f | %.6f | %.6f | %.3e |' % (
                r['st'], h['t'], abs(h['ratio']), abs(h['C']), run.OMEGA * h['t'] - cmath.phase(h['ratio']),
                run.OMEGA * h['t'] - cmath.phase(h['C']), h['l1']))
    L += ['', 'IGLOO: %d parcels per St, G2\' per-parcel residual at every time-stamped row (the gate\'s tolerance is 3e-6):' % gen.N_PARCELS, '',
          '| St | rows | worst &#124;z - C z0&#124; [m] | worst &#124;v - C\' z0&#124; [m/s] |', '|---|---|---|---|']
    for r in results:
        L.append('| %g | %d | %.2e | %.2e |' % (r['st'], len(r['rows']) + len(r['snap']), r['worst_z'], r['worst_v']))
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser(usage=__doc__)
    ap.add_argument('--check', action='store_true', help='exit 1 when a value leaves its tolerance')
    ap.add_argument('--work', default=str(HERE / 'work'))
    ap.add_argument('--reference', action='store_true', help='write the table and figures into reference/')
    ap.add_argument('--reuse', action='store_true', help='re-form the table and figures from the runs already in the work dir')
    ap.add_argument('--no-cache', action='store_true', help='run ICE even when a cached run matches, and store nothing')
    a = ap.parse_args()
    igloo_dir, igloo_bin, ice_ver, ice_bin, gen_path = resolve()

    sys.path.insert(0, str(ice_ver))
    import common                       # run.py imports the same module
    common.ICE_BIN = ice_bin
    run = load('ice_vortex_run', ice_ver / 'I-vortex-cloud/run.py')
    gen = load('make_vortex_case', gen_path)
    work = Path(a.work).resolve()
    work.mkdir(parents=True, exist_ok=True)
    cache = None if a.no_cache else HERE / '.cache'
    ice_md5 = md5_file(ice_bin)
    print('vortex-cloud 3-way: ICE %s (md5 %s), IGLOO %s, work %s, ICE cache %s'
          % (ice_bin, ice_md5, igloo_bin, work, cache if cache is not None else 'off'))

    seeds = gen.lattice()
    results, bad = [], []
    for st in ST_VALUES:
        tau = st / run.OMEGA
        try:
            ice_case, hist = ice_history(common, run, st, work, a.reuse, cache, ice_md5)
            snap, rows = igloo_run(gen, igloo_bin, st, work, a.reuse)
        except RuntimeError as exc:
            print('[FAIL] St = %g: %s' % (st, exc))
            sys.exit(1)
        T = snap[0][10]
        C, Cd = run.stretch(tau, T)
        ratio, slope = cloud(snap, seeds)
        dep = deposit(ice_case, [(p[0], p[1], p[3], p[4], seeds[p[9] - 1][2]) for p in snap])
        mass, centre, dslope = run.measure(ice_case, dep)
        exact_mapped = [(C * complex(s[0], s[1]), s[2]) for s in seeds]
        floor = run.l1_error(ice_case, deposit(ice_case, [(z.real, z.imag, 0.0, 0.0, m) for z, m in exact_mapped]), C)
        ref = sum(run.exact(x, y, C) for x, y in ice_case.centres)
        worst_z = worst_v = 0.0
        for rr in rows + snap:
            z0 = complex(seeds[rr[9] - 1][0], seeds[rr[9] - 1][1])
            Ct, Cdt = run.stretch(tau, rr[10])
            worst_z = max(worst_z, abs(complex(rr[0], rr[1]) - Ct * z0))
            worst_v = max(worst_v, abs(complex(rr[3], rr[4]) - Cdt * z0))
        results.append({'st': st, 'T': T, 'C': C, 'Cd': Cd, 'ratio': ratio, 'slope': slope,
                        'dep': dep, 'dep_ratio': centre / run.X0, 'dep_slope': dslope,
                        'dep_l1': run.l1_error(ice_case, dep, C), 'floor': floor, 'dep_mass': mass / ref - 1.0,
                        'ice': hist, 'ice_case': ice_case, 'rows': rows, 'snap': snap, 'seeds': seeds,
                        'worst_z': worst_z, 'worst_v': worst_v})
        e = hist[-1]
        ice_scale = abs(abs(e['ratio']) / abs(e['C']) - 1.0)
        ice_lag = abs(cmath.phase(e['C']) - cmath.phase(e['ratio']))
        ig_scale = abs(abs(ratio) - abs(C))
        ig_lag = abs(cmath.phase(ratio) - cmath.phase(C))
        print('St = %-5g ICE t %.6f: |C| %.6f (exact %.6f), lag err %.1e;  IGLOO t %.8f: |C| %.6f (exact %.6f), '
              'lag err %.1e, deposit L1 %.3e (kernel floor %.3e)'
              % (st, e['t'], abs(e['ratio']), abs(e['C']), ice_lag, T, abs(ratio), abs(C), ig_lag,
                 results[-1]['dep_l1'], floor))
        if ice_scale > TOL_ICE or ice_lag > TOL_ICE:
            bad.append('St = %g: ICE dilation error %.2e, lag error %.2e (tolerance %.0e)' % (st, ice_scale, ice_lag, TOL_ICE))
        if ig_scale > TOL_IGLOO or ig_lag > TOL_IGLOO:
            bad.append('St = %g: IGLOO |C| error %.2e, lag error %.2e (tolerance %.0e)' % (st, ig_scale, ig_lag, TOL_IGLOO))

    out = HERE / 'reference' if a.reference else work
    out.mkdir(parents=True, exist_ok=True)
    (out / 'table.md').write_text(table(results, run, gen))
    figures(results, run, igloo_dir, out)
    print('table and figures in %s' % out)
    if a.check:
        for b in bad:
            print('[FAIL] %s' % b)
        if bad:
            sys.exit(1)
        print('[PASS] ICE within %.0e of the closed form at its final time; IGLOO\'s cloud within %.0e at QUARTER'
              % (TOL_ICE, TOL_IGLOO))


if __name__ == '__main__':
    main()
