INK = '#303030'


def bilinear(field, case, x, y):
    h = case.Lx / case.nx
    fx, fy = (x - case.xn[0]) / h - 0.5, (y - case.yn[0]) / h - 0.5
    i, j = int(math.floor(fx)), int(math.floor(fy))
    if not (0 <= i < case.nx - 1 and 0 <= j < case.ny - 1):
        return float('nan')
    a, b = fx - i, fy - j
    f = lambda ii, jj: field[jj * case.nx + ii]
    return ((1 - a) * (1 - b) * f(i, j) + a * (1 - b) * f(i + 1, j)
            + (1 - a) * b * f(i, j + 1) + a * b * f(i + 1, j + 1))


def figures(results, run, igloo_dir, out):
    try:
        sys.path.insert(0, str(igloo_dir / 'tests'))
        import vv_style
        vv_style.apply()
    except ImportError:
        pass
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
    except ImportError:
        print('   matplotlib absent: no figures')
        return
    # lag and |C| against t: exact lines, ICE squares at its outputs, IGLOO dots from the rows
    fig, axes = plt.subplots(1, 2, figsize=(10.0, 4.0))
    tt = [i * 1.6 / 400 for i in range(401)]
    for k, r in enumerate(results):
        st, tau, col = r['st'], r['st'] / run.OMEGA, COLORS[k]
        Cs = [run.stretch(tau, t)[0] for t in tt]
        axes[0].plot(tt, [run.OMEGA * t - cmath.phase(C) for t, C in zip(tt, Cs)], color=col, lw=1.0)
        axes[1].plot(tt, [abs(C) for C in Cs], color=col, lw=1.0, label='St = %g' % st)
        pts = [(row[10], complex(row[0], row[1]) / complex(r['seeds'][row[9] - 1][0], r['seeds'][row[9] - 1][1]))
               for row in r['rows'] if row[9] % 97 == 0]
        axes[0].plot([p[0] for p in pts], [run.OMEGA * p[0] - cmath.phase(p[1]) for p in pts], 'o', ms=2.5,
                     color=col, alpha=0.5, mew=0)
        axes[1].plot([p[0] for p in pts], [abs(p[1]) for p in pts], 'o', ms=2.5, color=col, alpha=0.5, mew=0)
        axes[0].plot([h['t'] for h in r['ice']], [run.OMEGA * h['t'] - cmath.phase(h['ratio']) for h in r['ice']],
                     's', ms=6.0, mfc='none', mec=col, mew=1.2)
        axes[1].plot([h['t'] for h in r['ice']], [abs(h['ratio']) for h in r['ice']], 's', ms=6.0,
                     mfc='none', mec=col, mew=1.2)
    axes[0].set_xlabel(r'$t$ [s]'); axes[0].set_ylabel(r'lag $\Omega t - \arg\,C$ [rad]')
    axes[1].set_xlabel(r'$t$ [s]'); axes[1].set_ylabel(r'dilation $|C|$')
    from matplotlib.lines import Line2D
    handles = [Line2D([], [], color=COLORS[k], lw=1.5, label='St = %g' % r['st']) for k, r in enumerate(results)]
    handles += [Line2D([], [], color=INK, lw=1.5, label='exact'),
                Line2D([], [], ls='none', marker='s', mfc='none', mec=INK, label='ICE'),
                Line2D([], [], ls='none', marker='o', ms=3.0, color=INK, label='IGLOO (parcel rows)')]
    axes[0].legend(handles=handles, loc='upper left')
    fig.tight_layout()
    fig.savefig(str(out / 'vortex-3way-transition.svg'))
    plt.close(fig)

    # the quarter-turn density along the ray through the exact centroid
    fig, axes = plt.subplots(1, len(results), figsize=(3.2 * len(results), 3.4), sharey=True)
    for ax, r in zip(axes, results):
        C = r['C']
        e = C / abs(C)
        centre = C * run.X0
        span = 5.0 * run.SIG * abs(C)
        ss = [-span + 2.0 * span * i / 300 for i in range(301)]
        pts = [centre + s * e for s in ss]
        ice_case, ice_sol = r['ice_case'], r['ice'][-1]['sol']
        ax.plot(ss, [run.exact(p.real, p.imag, C) for p in pts], color=INK, lw=1.5, label='exact')
        ax.plot(ss, [bilinear(ice_sol['var'][0], ice_case, p.real, p.imag) for p in pts], color=C_ICE, lw=1.3,
                ls='--', label='ICE')
        ax.plot(ss, [bilinear(r['dep']['var'][0], ice_case, p.real, p.imag) for p in pts], color=C_IGLOO,
                lw=1.3, ls='-.', label='IGLOO (TSC deposit)')
        ax.set_title('St = %g' % r['st'])
        ax.set_xlabel(r'$s$ along the ray [m]')
    axes[0].set_ylabel(r'$\rho_p$ [kg/m$^3$]')
    axes[-1].legend(loc='upper right')
    fig.tight_layout()
    fig.savefig(str(out / 'vortex-3way-profile.svg'))
    plt.close(fig)


