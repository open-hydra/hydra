def skip(why):
    print('[SKIP] vortex-cloud 3-way comparison: %s' % why)
    sys.exit(SKIP)


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def resolve():
    hydra = os.environ.get('HYDRADIR')
    if not hydra:
        skip('HYDRADIR is not set')
    hydra = Path(hydra)
    igloo_dir = Path(os.environ.get('IGLOO_DIR', str(hydra / 'src/lib/IGLOO')))
    igloo_bin = Path(os.environ.get('IGLOO_BIN', str(igloo_dir / 'bin/IGLOO')))
    ice_dir = hydra / 'src/lib/ICE'
    ice_bin = Path(os.environ.get('ICE_BIN', str(ice_dir / 'bin/ICE')))
    ice_ver = ice_dir / 'test/verification'
    gen = igloo_dir / 'tests/tools/make_vortex_case.py'
    for path, what in ((ice_ver / 'common.py', "ICE's verification scripts"),
                       (ice_ver / 'I-vortex-cloud/run.py', "ICE's vortex case"),
                       (ice_bin, 'an ICE binary (ICE_BIN)'),
                       (gen, "IGLOO's case generator (IGLOO_DIR)"),
                       (igloo_bin, 'an IGLOO binary (IGLOO_BIN)')):
        if not path.exists():
            skip('no %s at %s' % (what, path))
    return igloo_dir, igloo_bin, ice_ver, ice_bin, gen


# -------------------------------------------------------------------------------- cache

def md5_file(path):
    h = hashlib.md5()
    with open(str(path), 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def ice_cache_key(ice_md5, case_dir, st):
    """md5 over the ICE binary, every file the run reads (input.ini, INPUT/) and the driver's own case
    parameters: another binary or another generated case is another entry."""
    h = hashlib.md5()
    h.update(('format %d\nice %s\nst %r\nn %d\n' % (CACHE_FORMAT, ice_md5, st, N)).encode())
    for f in [case_dir / 'input.ini'] + sorted((case_dir / 'INPUT').iterdir()):
        h.update(('%s %s\n' % (f.relative_to(case_dir), md5_file(f))).encode())
    return h.hexdigest()


def cache_restore(entry, outdir):
    """Copy a complete entry's outputs into outdir. An incomplete or corrupt entry is a miss: it is
    removed, and so is anything already copied, so the run that follows starts from an empty OUTPUT/."""
    if not entry.exists():
        return False
    try:
        rows = [ln.split() for ln in (entry / 'MANIFEST').read_text().splitlines() if ln.strip()]
        if sorted(name for _, name in rows) != sorted(ICE_OUTPUTS):
            raise ValueError('the manifest lists %d of the %d outputs' % (len(rows), len(ICE_OUTPUTS)))
        for digest, name in rows:
            data = gzip.decompress((entry / (name + '.gz')).read_bytes())
            if hashlib.md5(data).hexdigest() != digest:
                raise ValueError('%s does not match its md5' % name)
            (outdir / name).write_bytes(data)
        return True
    except (OSError, ValueError, EOFError, zlib.error) as exc:
        print('   cache entry %s unusable (%s): ICE runs again' % (entry.name, exc))
        shutil.rmtree(str(entry), ignore_errors=True)
        for name in ICE_OUTPUTS:
            if (outdir / name).exists():
                (outdir / name).unlink()
        return False


def cache_store(cache, key, outdir):
    """Store a run's outputs as <cache>/<key>, written in a temp dir and renamed once complete."""
    if any(not (outdir / name).exists() for name in ICE_OUTPUTS):
        return
    tmp = cache / ('%s.tmp-%d' % (key, os.getpid()))
    try:
        shutil.rmtree(str(tmp), ignore_errors=True)
        tmp.mkdir(parents=True)
        lines = []
        for name in ICE_OUTPUTS:
            data = (outdir / name).read_bytes()
            (tmp / (name + '.gz')).write_bytes(gzip.compress(data, compresslevel=6))
            lines.append('%s %s' % (hashlib.md5(data).hexdigest(), name))
        (tmp / 'MANIFEST').write_text('\n'.join(lines) + '\n')
        os.rename(str(tmp), str(cache / key))      # fails if a concurrent run stored the entry first
    except OSError:
        shutil.rmtree(str(tmp), ignore_errors=True)


# ---------------------------------------------------------------------------------- ICE

def ice_history(common, run, st, work, reuse=False, cache=None, ice_md5=None):
    """run.py's case at St with numbered intermediate solutions; measure() on each."""
    ph = common.Physics()
    tau = st / run.OMEGA
    dp = math.sqrt(18.0 * ph.mu * tau / ph.rho_al)
    volume = ph.rho_al * (4.0 / 3.0) * math.pi * (0.5 * dp) ** 3
    rundir = work / ('ice-st%g' % st)
    reuse = reuse and (rundir / 'OUTPUT/part-field.tec').exists()
    # Case() empties its directory: a reused run keeps its outputs, the geometry comes from a scratch twin
    case = common.Case(work / 'ice-geometry' if reuse else rundir, nx=N, ny=N, Lx=2.0 * run.HALF,
                       Ly=2.0 * run.HALF, Lz=2.0 * run.HALF / N, x0=-run.HALF, y0=-run.HALF)
    case.particles(rho=run.profile, u=lambda x, y: -run.OMEGA * y, v=lambda x, y: run.OMEGA * x, w=0.0,
                   T=ph.Tg, n=lambda x, y: run.profile(x, y) / volume)
    case.gas(rho=ph.rho_g, u=lambda x, y: -run.OMEGA * y, v=lambda x, y: run.OMEGA * x, w=0.0,
             T=ph.Tg, R=ph.R, gam=ph.gam, k=ph.kg, mu=ph.mu)
    case.boundaries('extrapolation')
    case.ini(t_end=run.QUARTER, cfl=0.4, dt_max=1.0e-3, drag='Stokes', heat='Stokes',
             rho_al=ph.rho_al, cs=ph.cs)
    # Case.ini() owns [ICE-IO]; the two history keys go into that section of the written file.
    ini = case.dir / 'input.ini'
    text = ini.read_text()
    if text.count('[ICE-IO]\n') != 1:
        raise RuntimeError('unexpected input.ini layout in %s' % case.dir)
    ini.write_text(text.replace('[ICE-IO]\n', '[ICE-IO]\n%-22s = false\n%-22s = %r\n'
                                % ('sol-overwrite', 'sol-dtime', run.QUARTER / 8.0)))
    if not reuse:
        entry = cache / ice_cache_key(ice_md5, case.dir, st) if cache is not None else None
        if entry is not None and cache_restore(entry, case.dir / 'OUTPUT'):
            print('   ICE St = %g: cached run %s' % (st, entry.name))
        else:
            common.run_ice(case.dir, threads=1)
            if entry is not None:
                cache.mkdir(parents=True, exist_ok=True)
                cache_store(cache, entry.name, case.dir / 'OUTPUT')
    hist = []
    for k in list(range(1, 8)) + ['']:
        path = rundir / ('OUTPUT/part-field%s.tec' % k)
        if not path.exists():
            continue
        sol = common.read_solution(path)
        t = sol['time']
        C, Cd = run.stretch(tau, t)
        mass, centre, slope = run.measure(case, sol)
        ref = sum(run.exact(x, y, C) for x, y in case.centres)
        hist.append({'t': t, 'C': C, 'Cd': Cd, 'ratio': centre / run.X0, 'slope': slope,
                     'l1': run.l1_error(case, sol, C), 'mass': mass / ref - 1.0, 'sol': sol})
    if not hist or hist[-1]['t'] < run.QUARTER:
        raise RuntimeError('ICE left no final solution past QUARTER in %s' % rundir)
    return case, hist


# -------------------------------------------------------------------------------- IGLOO

def run_igloo(igloo_bin, case_dir):
    def stack():
        try:
            resource.setrlimit(resource.RLIMIT_STACK, (resource.RLIM_INFINITY, resource.RLIM_INFINITY))
        except (ValueError, OSError):
            pass
    env = dict(os.environ, OMP_NUM_THREADS='1', KMP_STACKSIZE='100M')
    (case_dir / 'OUTPUT').mkdir(exist_ok=True)
    with open(str(case_dir / 'run_out.txt'), 'w') as out, open(str(case_dir / 'run_err.txt'), 'w') as err:
        rc = subprocess.call([str(igloo_bin)], cwd=str(case_dir), stdout=out, stderr=err, env=env,
                             preexec_fn=stack)
    if rc != 0:
        raise RuntimeError('IGLOO failed (exit %d) in %s' % (rc, case_dir))


def read_rows(path, ncol=11):
    rows = []
    for ln in open(str(path)):
        t = ln.split()
        if len(t) != ncol:
            continue
        try:
            rows.append([float(v) for v in t[:9]] + [int(t[9])] + [float(v) for v in t[10:]])
        except ValueError:
            continue
    return rows


def igloo_run(gen, igloo_bin, st, work, reuse=False):
    """One vortex-cloud dir at St (INPUT shared), run; snapshot and trajectory rows."""
    case_dir = work / ('iglo-st%g' % st)
    if reuse and (case_dir / 'OUTPUT/snapshot-A.dat').exists():
        return read_rows(case_dir / 'OUTPUT/snapshot-A.dat'), read_rows(case_dir / 'OUTPUT/trajectories-A.dat')
    shared = work / 'iglo-INPUT'
    if not (shared / 'solfile.tec').exists():
        tmp = work / 'iglo-inputs'
        gen.write_inputs(str(tmp))
        if shared.exists():
            shutil.rmtree(str(shared))
        (tmp / 'INPUT').rename(shared)
        shutil.rmtree(str(tmp))
    if case_dir.exists():
        shutil.rmtree(str(case_dir))
    case_dir.mkdir(parents=True)
    (case_dir / 'INPUT').symlink_to(shared.resolve())
    gen.write_input(str(case_dir), st)
    run_igloo(igloo_bin, case_dir)
    snap = read_rows(case_dir / 'OUTPUT/snapshot-A.dat')
    rows = read_rows(case_dir / 'OUTPUT/trajectories-A.dat')
    if len(snap) != gen.N_PARCELS:
        raise RuntimeError('IGLOO snapshot holds %d parcels, expected %d (%s)' % (len(snap), gen.N_PARCELS, case_dir))
    return snap, rows


def cloud(snap, seeds):
    """Mass-weighted centroid ratio z / z0 and velocity slope of the snapshot (weights mdot by ID)."""
    w = [seeds[r[9] - 1][2] for r in snap]
    z = [complex(r[0], r[1]) for r in snap]
    v = [complex(r[3], r[4]) for r in snap]
    zbar0 = sum(s[2] * complex(s[0], s[1]) for s in seeds) / sum(s[2] for s in seeds)
    zbar = sum(a * b for a, b in zip(w, z)) / sum(w)
    slope = (sum(a * b * c.conjugate() for a, b, c in zip(w, v, z)) / sum(a * abs(c) ** 2 for a, c in zip(w, z)))
    return zbar / zbar0, slope


def tsc(pos, x0, h, n):
    """Triangular-shaped-cloud weights along one axis: [(cell, weight)] for a cell-centred grid."""
    s = (pos - x0) / h - 0.5
    i = int(math.floor(s + 0.5))
    d = s - i
    out = []
    for c, wt in ((i - 1, 0.5 * (0.5 - d) ** 2), (i, 0.75 - d * d), (i + 1, 0.5 * (0.5 + d) ** 2)):
        if 0 <= c < n:
            out.append((c, wt))
    return out


def deposit(case, parcels):
    """Parcels (x, y, u, v, mass) on ICE's grid: sol['var'] = [rho, u, v] in ICE's cell order."""
    h, vol = case.Lx / case.nx, (case.Lx / case.nx) * (case.Ly / case.ny) * case.Lz
    mass = [0.0] * (case.nx * case.ny)
    mu = [0.0] * len(mass)
    mv = [0.0] * len(mass)
    for x, y, u, v, m in parcels:
        for i, wx in tsc(x, case.xn[0], h, case.nx):
            for j, wy in tsc(y, case.yn[0], h, case.ny):
                c = j * case.nx + i
                w = m * wx * wy
                mass[c] += w
                mu[c] += w * u
                mv[c] += w * v
    rho = [a / vol for a in mass]
    uu = [b / a if a > 0.0 else 0.0 for a, b in zip(mass, mu)]
    vv = [b / a if a > 0.0 else 0.0 for a, b in zip(mass, mv)]
    return {'var': [rho, uu, vv]}


