#!/usr/bin/env python3
"""vortex-cloud: ICE's verification case I solved by ICE (Eulerian moments) and by IGLOO
(Lagrangian parcels), each set beside the exact solution.

A particle cloud is released at the local gas velocity into a frozen solid-body vortex,
u_g = i Omega z. With Stokes drag and a uniform diameter every parcel moves as z(t) = C(t) z0, so
the cloud rotates by arg C (lagging Omega t) and dilates by |C|, and the density is
rho_p0(z / C) / |C|^2 (ICE's test/verification/I-vortex-cloud/run.py). For St = 0.01, 0.1, 1, 10:

  ICE    run.py's case with sol-overwrite = false and sol-dtime = QUARTER/8, so one run leaves
         the seven intermediate solutions part-field1..7.tec beside the final part-field.tec;
         run.py's measure() and l1_error() on each, against the exact solution at the file's
         own SOLUTIONTIME (the last one is ICE's first step past QUARTER, 1.571 s).
  IGLOO  the four dirs of tests/standard/vortex-cloud-st* regenerated by make_vortex_case.py
         and run at OMP_NUM_THREADS=1: 1672 parcels stopped at QUARTER (time-end), every row
         time-stamped (out-time). The cloud's own centroid and velocity slope from
         snapshot-A.dat (weights mdot by ID), and the same parcels deposited on ICE's 96 x 96
         grid with the triangular-shaped-cloud kernel, measured by ICE's own measure() and
         l1_error(). The deposit of the exactly mapped lattice gives the kernel's own L1 floor.

ICE's runs are cached: its output is a function of its binary and of the case the driver writes,
so each run is stored under .cache/<key> beside this script, the key being the md5 of the ICE
binary, of every file the run reads and of the case parameters. A matching entry is copied back
instead of running ICE; a missing, incomplete or corrupt one runs ICE and stores the result.
IGLOO always runs. --no-cache runs ICE regardless and stores nothing.

Writes <work>/table.md and, when matplotlib is present, <work>/vortex-3way-transition.svg (lag
and |C| against t) and <work>/vortex-3way-profile.svg (the quarter-turn density along the ray
through the exact centroid); --reference writes the three into reference/ instead.

    compare.py [--check] [--work DIR] [--reference] [--reuse] [--no-cache]

Environment: HYDRADIR (required); IGLOO_DIR (default $HYDRADIR/src/lib/IGLOO) for the case
generator, IGLOO_BIN (default $IGLOO_DIR/bin/IGLOO); ICE_BIN (default
$HYDRADIR/src/lib/ICE/bin/ICE, ICE's standalone build).

Exit: 0 when the table is formed; with --check, also 1 when IGLOO's cloud departs from the
closed form at QUARTER by more than TOL_IGLOO (the per-parcel gate's 3e-6 m over X0) or ICE's
dilation or lag departs from the closed form at its own final time by more than run.py's 5e-3;
1 when a solver fails; 77 (skipped) when HYDRADIR is unset or ICE's verification scripts, an ICE
binary, IGLOO's generator or an IGLOO binary is missing.
"""
